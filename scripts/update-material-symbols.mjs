#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import process from 'node:process'
import {
  MATERIAL_ICON_BY_SEMANTIC_ID,
  MATERIAL_UI_GLYPHS,
} from '../src/features/record/metadata/semanticCatalog.ts'
import { SHELL_MATERIAL_GLYPHS } from '../src/app/shell/materialGlyphs.ts'

const ROOT = path.resolve(import.meta.dirname, '..')
const FONT_PATH = path.join(
  ROOT,
  'src/assets/material-symbols-rounded-subset.woff2',
)
const MANIFEST_PATH = path.join(
  ROOT,
  'src/assets/material-symbols-rounded-subset.json',
)
const CSS_PATH = path.join(
  ROOT,
  'src/assets/material-symbols-rounded-subset.css',
)
const GOOGLE_FONTS_CSS_API = 'https://fonts.googleapis.com/css2'
const FAMILY = 'Material Symbols Rounded:opsz,wght,FILL,GRAD@24,400,1,0'
const USER_AGENT =
  'Mozilla/5.0 AppleWebKit/537.36 Chrome/151.0.0.0 Safari/537.36'

export function selectedMaterialIconNames() {
  return [
    ...new Set([
      ...Object.values(MATERIAL_ICON_BY_SEMANTIC_ID),
      ...Object.values(MATERIAL_UI_GLYPHS),
      ...Object.values(SHELL_MATERIAL_GLYPHS),
    ]),
  ].sort()
}

export function googleFontsCssUrl(iconNames = selectedMaterialIconNames()) {
  const url = new URL(GOOGLE_FONTS_CSS_API)
  url.searchParams.set('family', FAMILY)
  url.searchParams.set('icon_names', iconNames.join(','))
  url.searchParams.set('display', 'block')
  return url.href
}

export function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex')
}

export function generatedSubsetCss(font) {
  return `/* Generated by \`pnpm icons:update\`; do not edit by hand. */
@font-face {
  font-family: 'Material Symbols Rounded';
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url('data:font/woff2;base64,${font.toString('base64')}')
    format('woff2');
}
`
}

export function validateSubset({
  font,
  manifest,
  expectedIconNames = selectedMaterialIconNames(),
}) {
  const problems = []
  if (manifest.manifestVersion !== 1) {
    problems.push('manifest version is unsupported')
  }
  if (!font.subarray(0, 4).equals(Buffer.from('wOF2'))) {
    problems.push('font is not WOFF2')
  }
  if (font.byteLength !== manifest.byteLength) {
    problems.push('font byte length does not match its manifest')
  }
  if (sha256(font) !== manifest.sha256) {
    problems.push('font checksum does not match its manifest')
  }
  if (manifest.family !== FAMILY) {
    problems.push('font family/axes do not match the generator')
  }
  try {
    if (new URL(manifest.fontSourceUrl).hostname !== 'fonts.gstatic.com') {
      problems.push('font source is not Google Fonts')
    }
  } catch {
    problems.push('font source URL is invalid')
  }
  if (manifest.cssApiUrl !== googleFontsCssUrl(expectedIconNames)) {
    problems.push('CSS API URL does not match the selected icons')
  }
  if (
    JSON.stringify(manifest.iconNames) !== JSON.stringify(expectedIconNames)
  ) {
    problems.push('manifest icon selection is stale')
  }
  return problems
}

function fontUrlFromCss(css) {
  const match = /src:\s*url\((https:\/\/fonts\.gstatic\.com\/[^)]+)\)/.exec(css)
  if (!match?.[1]) {
    throw new Error('Google Fonts CSS did not contain a font URL')
  }
  return match[1]
}

async function fetchOk(url, options) {
  const response = await fetch(url, options)
  if (!response.ok) {
    throw new Error(`Request failed (${response.status}): ${url}`)
  }
  return response
}

async function update() {
  const iconNames = selectedMaterialIconNames()
  const cssApiUrl = googleFontsCssUrl(iconNames)
  const cssResponse = await fetchOk(cssApiUrl, {
    headers: { 'User-Agent': USER_AGENT },
    redirect: 'error',
  })
  const fontUrl = fontUrlFromCss(await cssResponse.text())
  const fontResponse = await fetchOk(fontUrl, {
    headers: { 'User-Agent': USER_AGENT },
    redirect: 'error',
  })
  const font = Buffer.from(await fontResponse.arrayBuffer())
  const manifest = {
    manifestVersion: 1,
    family: FAMILY,
    iconNames,
    cssApiUrl,
    fontSourceUrl: fontUrl,
    byteLength: font.byteLength,
    sha256: sha256(font),
  }
  const problems = validateSubset({
    font,
    manifest,
    expectedIconNames: iconNames,
  })
  if (problems.length > 0) {
    throw new Error(
      `Refusing invalid Material Symbols subset: ${problems.join('; ')}`,
    )
  }
  await mkdir(path.dirname(FONT_PATH), { recursive: true })
  await writeFile(FONT_PATH, font)
  await writeFile(MANIFEST_PATH, `${JSON.stringify(manifest, null, 2)}\n`)
  await writeFile(CSS_PATH, generatedSubsetCss(font))
  console.log(
    `material-symbols: wrote ${iconNames.length} glyphs, ${font.byteLength} bytes`,
  )
}

async function check() {
  let font
  let manifest
  let css
  try {
    font = await readFile(FONT_PATH)
    manifest = JSON.parse(await readFile(MANIFEST_PATH, 'utf8'))
    css = await readFile(CSS_PATH, 'utf8')
  } catch (error) {
    throw new Error(
      `Material Symbols subset is missing or unreadable; run pnpm icons:update. ${String(error)}`,
      { cause: error },
    )
  }
  const problems = validateSubset({ font, manifest })
  if (css !== generatedSubsetCss(font)) {
    problems.push('generated stylesheet does not match the font bytes')
  }
  if (problems.length > 0) {
    throw new Error(
      `Material Symbols subset is stale; run pnpm icons:update. ${problems.join('; ')}`,
    )
  }
  console.log(
    `material-symbols: ${manifest.iconNames.length} glyphs and checksum verified`,
  )
}

async function main() {
  if (process.argv.includes('--check')) await check()
  else await update()
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : String(error))
    process.exitCode = 1
  })
}
